/** Replace each {…} in order. A single array argument is unwrapped. */
export function fill(
  template: string,
  ...values: Array<string | number | readonly (string | number)[]>
): string {
  const first = values[0];
  const list: readonly (string | number)[] =
    values.length === 1 && Array.isArray(first) ? first : (values as (string | number)[]);
  let index = 0;
  return String(template).replace(/\{…\}/g, () => String(list[index++] ?? ""));
}
